#!/usr/bin/env python3
"""Export the original header artwork as a Flash-resident LVGL image."""

from pathlib import Path
import subprocess


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/images/badge-lobster.svg"
OUTPUT = ROOT / "assets/images/badge_lobster_22.c"
SIZE = 22


def main():
    pixels = subprocess.check_output([
        "magick", "-background", "none", str(SOURCE), "-depth", "8", "BGRA:-",
    ])
    if len(pixels) != SIZE * SIZE * 4:
        raise ValueError("The header artwork must remain 22 × 22 pixels")
    rows = [
        "    " + ", ".join(f"0x{byte:02x}" for byte in pixels[i:i + 16]) + ","
        for i in range(0, len(pixels), 16)
    ]
    OUTPUT.write_text(
        '/* Original project artwork; generated by python3 tools/make_lobster.py. */\n'
        '#include "lvgl.h"\n\n'
        'static const uint8_t pixels[] = {\n' + "\n".join(rows) + '\n};\n\n'
        'const lv_image_dsc_t badge_lobster_22 = {\n'
        '    .header = {\n'
        '        .magic = LV_IMAGE_HEADER_MAGIC,\n'
        '        .cf = LV_COLOR_FORMAT_ARGB8888,\n'
        f'        .w = {SIZE}, .h = {SIZE}, .stride = {SIZE * 4},\n'
        '    },\n'
        '    .data_size = sizeof(pixels),\n'
        '    .data = pixels,\n'
        '};\n', encoding="utf-8",
    )
    print(f"Generated {OUTPUT.relative_to(ROOT)} ({len(pixels)} bytes of image data)")


if __name__ == "__main__":
    main()
